#!/usr/bin/env node
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = join(root, "content", "public");
const outFile = join(root, "lib", "public-docs.generated.ts");

function walk(dir) {
  /** @type {string[]} */
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(path));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}

const docs = {};
for (const file of walk(publicDir).sort()) {
  const rel = relative(publicDir, file).split("\\").join("/");
  if (rel.startsWith("private/") || rel.includes("/private/")) {
    throw new Error(`Refusing to bundle private path: ${rel}`);
  }
  docs[rel] = readFileSync(file, "utf8");
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `/* generated by scripts/bundle-public.mjs — do not edit */
export const PUBLIC_DOCS: Record<string, string> = ${JSON.stringify(docs, null, 2)};
`,
);
console.log(`Bundled ${Object.keys(docs).length} public docs → lib/public-docs.generated.ts`);
